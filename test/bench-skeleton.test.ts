import { afterAll, expect, test } from "bun:test";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, realpathSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { analyzeProject } from "../src/core/pipeline";
import { generateSynthetic, runBenchmark, ToolRecorder } from "../src/core/bench";
import { validateSkeleton } from "../src/core/bench/skeleton";
const temp = realpathSync(mkdtempSync(join(tmpdir(), "skyplate-bench-skeleton-test-")));
afterAll(() => rmSync(temp, { recursive: true, force: true }));

test("permuted skeleton regenerates the exact tree and code graph with coarse numeric attributes", async () => {
  const original = join(temp, "private-original");
  mkdirSync(join(original, "private-alpha", "private-beta"), { recursive: true });
  mkdirSync(join(original, "private-gamma"));
  writeFileSync(join(original, "private-alpha", "one.ts"), 'import "./private-beta/two";\nexport type Value = number;\n');
  writeFileSync(join(original, "private-alpha", "private-beta", "two.ts"), 'import "../../private-gamma/three";\nexport type Value = number;\n');
  writeFileSync(join(original, "private-gamma", "three.ts"), 'import "../private-alpha/one";\nexport type Value = number;\n');
  writeFileSync(join(original, "root.ts"), 'import type { Value } from "./private-alpha/one";\n');
  const recorder = new ToolRecorder();
  recorder.record({ tool: "files", durationMs: 7, responseBytes: 100 });
  const b = await runBenchmark(original, { skeleton: true, analysis: { git: false, symbols: false, workers: 1 }, recorder });
  expect(b.failures).toEqual([]);
  expect(b.session.calls[0]!.tool).toBe("files");
  const s = b.skeleton!;
  validateSkeleton(s);
  expect(JSON.stringify(s)).not.toContain("private");
  const generated = join(temp, "synthetic");
  await generateSynthetic(s, generated);
  const result = await analyzeProject(generated, { git: false, symbols: false, source: false, workers: 1 });
  expect(result.report.files.length).toBe(s.files.length);
  expect(result.report.dirs.length).toBe(s.dirs.length);
  const synthId = (id: number) => Number(result.report.files[id]!.name.match(/^f(\d+)\.ts$/)![1]);
  const actual = result.report.edges.from.map((f, i) => `${synthId(f)}:${synthId(result.report.edges.to[i]!)}`).sort();
  expect(actual).toEqual(s.edges.map((e) => `${e.from}:${e.to}`).sort());
  const originalFanout = s.dirs.map((_, i) => s.dirs.filter((d) => d.parent === i).length + s.files.filter((f) => f.dir === i).length).sort((a, c) => a - c);
  expect(result.report.dirs.map((d) => d.dirs.length + d.files.length).sort((a, c) => a - c)).toEqual(originalFanout);
  expect(result.report.edges.typeOnly?.length).toBe(1);
  await expect(generateSynthetic(s, generated)).rejects.toThrow();
  const empty = join(temp, "existing-empty");
  mkdirSync(empty);
  await expect(generateSynthetic(s, empty)).rejects.toThrow();
  const link = join(temp, "linked");
  symlinkSync(original, link);
  await expect(generateSynthetic(s, link)).rejects.toThrow();
  const malformed = structuredClone(s);
  malformed.dirs[0]!.parent = 0;
  await expect(generateSynthetic(malformed, join(temp, "invalid"))).rejects.toThrow();
  expect(existsSync(join(temp, "invalid"))).toBe(false);
}, 30000);
